const galleryMessages: Record<GalleryLanguage, { gallery: typeof zh }> = {
  "en-US": { gallery: en },
  "zh-CN": { gallery: zh },
};

function resolveGalleryLanguage(locale: string): GalleryLanguage {
  return locale.startsWith("zh") ? "zh-CN" : "en-US";
}

export function mergeGalleryMessages(config: I18nOptions): I18nOptions {
  const messages = (config.messages ?? {}) as Record<string, any>;

  for (const locale of Object.keys(messages)) {
    const language = resolveGalleryLanguage(locale);
    messages[locale] = {
      ...messages[locale],
      ...galleryMessages[language],
    };
  }

  return {
    ...config,
    messages,
  };
}
